import 'dotenv/config';
// Tokens issued by this server process are invalidated whenever the backend restarts.
process.env.SERVER_SESSION_ID = crypto.randomUUID();
import http from 'http';
import crypto from 'node:crypto';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { Server } from 'socket.io';
import jwt from 'jsonwebtoken';
import Stripe from 'stripe';
import connectDB from './config/db.js';
import User from './models/User.js';
import Course from './models/Course.js';
import Enrollment from './models/Enrollment.js';
import Message from './models/Message.js';
import authRoutes from './routes/auth.js';
import courseRoutes from './routes/courses.js';
import learningRoutes from './routes/learning.js';
import adminRoutes from './routes/admin.js';
import discussionRoutes from './routes/discussions.js';
import quizRoutes from './routes/quizzes.js';
import uploadRoutes from './routes/uploads.js';
import paymentRoutes from './routes/payments.js';
const app=express();
const allowedOrigin=process.env.CLIENT_URL||'http://localhost:5173';
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
app.use(cors({origin:allowedOrigin,credentials:true}));
app.post('/api/payments/webhook',express.raw({type:'application/json'}),async(req,res)=>{try{if(!process.env.STRIPE_SECRET_KEY||!process.env.STRIPE_WEBHOOK_SECRET)return res.status(503).send('Payments webhook is not configured');const stripe=new Stripe(process.env.STRIPE_SECRET_KEY);const event=stripe.webhooks.constructEvent(req.body,req.headers['stripe-signature'],process.env.STRIPE_WEBHOOK_SECRET);if(event.type==='checkout.session.completed'){const session=event.data.object;if(session.payment_status==='paid'){const {studentId,courseId}=session.metadata||{};if(studentId&&courseId)await Enrollment.findOneAndUpdate({student:studentId,course:courseId},{$set:{status:'approved',enrolledAt:new Date()}},{upsert:true,new:true,setDefaultsOnInsert:true});}}res.json({received:true});}catch(error){console.error('Stripe webhook error:',error.message);res.status(400).send(`Webhook Error: ${error.message}`)}});
app.use(express.json({limit:'2mb'}));
app.use(morgan('dev'));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:100}),authRoutes);
app.get('/api/health',(req,res)=>res.json({status:'ok',app:'LearnEase Pro'}));
app.use('/api/courses',courseRoutes);
app.use('/api/learning',learningRoutes);
app.use('/api/admin',adminRoutes);
app.use('/api/discussions',discussionRoutes);
app.use('/api/quizzes',quizRoutes);
app.use('/api/uploads',uploadRoutes);
app.use('/api/payments',paymentRoutes);
app.use((req,res)=>res.status(404).json({message:'Route not found'}));
app.use((err,req,res,next)=>{console.error(err);const status=err.name==='ValidationError'||err.name==='MulterError'?400:500;res.status(status).json({message:status===400?err.message:'Server error'})});
const server=http.createServer(app);
const io=new Server(server,{cors:{origin:allowedOrigin,methods:['GET','POST']}});
io.use(async(socket,next)=>{try{const token=socket.handshake.auth?.token;if(!token)return next(new Error('Authentication required'));const decoded=jwt.verify(token,process.env.JWT_SECRET);const user=await User.findById(decoded.id);if(!user)return next(new Error('User not found'));if(decoded.sid!==process.env.SERVER_SESSION_ID)return next(new Error('Session expired because the server restarted'));socket.user=user;next()}catch{next(new Error('Invalid or expired token'))}});
async function canJoin(courseId,user){if(user.role==='admin')return true;
const course=await Course.findById(courseId);
if(!course)return false;
if(user.role==='instructor'&&course.instructor.equals(user._id))return true;
return !!await Enrollment.exists({course:courseId,student:user._id,status:'approved'})}
io.on('connection',socket=>{socket.on('course:join',async(courseId,ack)=>{try{if(!await canJoin(courseId,socket.user))return ack?.({error:'Approved course access required'});socket.join(`course:${courseId}`);ack?.({ok:true})}catch{ack?.({error:'Unable to join course chat'})}});socket.on('course:message',async({courseId,body},ack)=>{try{const text=String(body||'').trim();if(!text||text.length>2000)return ack?.({error:'Message must be between 1 and 2000 characters'});if(!await canJoin(courseId,socket.user))return ack?.({error:'Course access required'});const message=await Message.create({course:courseId,sender:socket.user._id,body:text});const populated=await message.populate('sender','name role');io.to(`course:${courseId}`).emit('course:message',populated);ack?.({ok:true})}catch{ack?.({error:'Unable to send message'})}})});
const port=process.env.PORT||5000;
connectDB().then(()=>server.listen(port,()=>console.log(`API and Socket.IO listening on ${port}`))).catch(err=>{console.error('Database connection failed',err);process.exit(1)});
