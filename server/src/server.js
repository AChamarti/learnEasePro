import 'dotenv/config';
import express from 'express';import cors from 'cors';import helmet from 'helmet';import morgan from 'morgan';import rateLimit from 'express-rate-limit';
import connectDB from './config/db.js';
import authRoutes from './routes/auth.js';import courseRoutes from './routes/courses.js';import learningRoutes from './routes/learning.js';import adminRoutes from './routes/admin.js';import discussionRoutes from './routes/discussions.js';
const app=express();
app.use(helmet());app.use(cors({origin:process.env.CLIENT_URL||'http://localhost:5173'}));app.use(express.json({limit:'2mb'}));app.use(morgan('dev'));
app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:100}),authRoutes);
app.get('/api/health',(req,res)=>res.json({status:'ok',app:'LearnEase Pro'}));
app.use('/api/courses',courseRoutes);app.use('/api/learning',learningRoutes);app.use('/api/admin',adminRoutes);app.use('/api/discussions',discussionRoutes);
app.use((req,res)=>res.status(404).json({message:'Route not found'}));
app.use((err,req,res,next)=>{console.error(err);res.status(err.name==='ValidationError'?400:500).json({message:err.name==='ValidationError'?err.message:'Server error'})});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`API listening on ${port}`))).catch(err=>{console.error('Database connection failed',err);process.exit(1)});
